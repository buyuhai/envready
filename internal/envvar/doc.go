// Package envvar 负责环境变量：写入、备份、回读校验、版本切换与撤销。
//
// 负责：
//   - Windows：只写 HKCU\Environment，保持 REG_EXPAND_SZ 类型，读写原始未展开值，
//     修改后广播 WM_SETTINGCHANGE，随后回读校验；
//   - Unix：判定登录 shell（账号数据库优先，不信 $SHELL），按组件归组写幂等块
//     （zsh/bash/fish 三种语法分别处理），换版本时整块替换而非追加；
//   - 备份（改前先落盘）与"意图记录"（崩溃后可判定并修复半成品状态）；
//   - 一键还原，以及只清理自己写入的内容。
//
// 不负责：下载、解压、界面展示。
//
// 关键约束：绝不写 HKLM / 系统级 PATH；绝不跳过对 fish 的语法区分；
// 绝不静默失败——每一步写入都要回读校验。详见设计文档 07。
