//   - 错误呈现的三行结构（发生了什么 / 为什么 / 你可以怎么做）；
//   - 授权询问的措辞（逐项、默认安全）。
//
// 不负责：任何业务逻辑；也不直接拼装错误字符串（技术细节进日志，不进界面）。
//
// 关键约束：界面上不允许直接出现术语表左列的技术词；失败必须给出至少一条出路。
