// Package archive 负责归档识别与解压。
//
// 负责：
//   - 以文件头魔术字节识别格式（zip / tar.gz / tar.xz / tar / 7z / rpm），不看扩展名；
//   - 解压到暂存目录，支持 strip_root（是否去掉顶层目录）；
//   - 保留符号链接与 Unix 权限位（macOS 的程序包必须靠它们才能运行）；
//   - 7z 的三级降级：系统 tar.exe → 已安装 7-Zip → 下载官方 7zr.exe（含固定哈希校验）；
//   - 解压进度与取消。
//
// 不负责：
//   - 下载（download）、判断"该不该装"（install）。
//
// 关键约束：格式识别必须基于内容；未知/不支持的格式要明确报错，不猜。详见设计文档 05。
