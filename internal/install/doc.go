// Package install 负责安装编排：把一个已下载的包变成"可用且已验证"的组件。
//
// 负责八步流水线：
//  1. 准入检查（磁盘空间、目录可写、依赖、冲突）；
//  2. 下载（委托 download）；
//  3. 完整性校验；
//  4. 解压到 <ENV_ROOT>/<key>/.stage-<版本>/；
//  5. 内容校验（清单的 expect_files：区分"解压成功"与"解压出正确的东西"）；
//  6. 原子落盘（.stage- → <key>-<版本>）；
//  7. 配置环境变量（委托 envvar）；
//  8. 自检（真正执行 verify 命令并核对版本）+ 呈现人工提示。
//
// 不负责：直接发 HTTP 请求、直接写注册表、直接操作界面。
//
// 关键约束：进度条走完不等于装好，必须自检通过才算成功；不收录需要用户先有编译器的组件。
// 详见设计文档 05。
