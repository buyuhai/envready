// Package download 负责下载引擎：把"一个 URL"变成"一个校验过的本地文件"。
//
// 负责：
//   - 多镜像测速择优与失败换源；
//   - .part 分片 + .part.meta 续传元数据，断点续传与"服务端不支持 Range 时安全重下"；
//   - 分层超时（连接 / 首字节 / 空闲），不设大文件的整体超时；
//   - 重试与退避（带随机抖动），按错误分类决定能否重试；
//   - 代理（设置项 / 环境变量 / 系统代理）；
//   - 边下边算 SHA-256（续传时从头重算）；
//   - 进度上报与取消（在数据块边界响应）。
//
// 不负责：
//   - 解析清单、解压、写环境变量。
//
// 关键约束：探测与下载一律用 GET + Range，不用 HEAD（实测多个站点 HEAD 会超时误判）；
// 绝不因为证书错误而降级为不校验。详见设计文档 06、11。
package download
