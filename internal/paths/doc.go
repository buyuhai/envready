// 在三平台上的位置，以及它们下面的固定子目录。
//
// 负责：
//   - 三平台目录规则（%LOCALAPPDATA% / ~/Library/Application Support / XDG_DATA_HOME）；
//   - 指针文件、版本目录、下载缓存、日志目录的路径拼接；
//   - 路径规范化（含用户名带空格或中文的情况）。
//
// 不负责：
//   - 创建目录（本包只算路径，创建由调用方决定）；
//   - 判断可写性（那属于启动期预检）。
//
// 关键约束：程序根（我们的）与环境根（用户资产）必须严格分开，
// 更新器只允许写程序根。详见设计文档 02。
